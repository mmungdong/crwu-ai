import * as React from 'react'
import { Button } from '../../../../ui/components/index.ts'
import type {
  ValuationWorkflowClarification,
  ValuationWorkflowFieldSourceKind,
  ValuationWorkflowNodeFieldView,
  ValuationWorkflowNodeView,
} from '../../../../../shared/contracts/valuation-workflow.ts'
import { VALUATION_WORKFLOW_CLASSES as W } from '../../styles/workflow.ts'
import { sourceKindLabelOf } from './model.ts'
import { StructuredValue } from '../../../../ui/workflow/StructuredValue.tsx'
import { ClarificationPanel } from './ClarificationPanel.tsx'
import { QuestionnairePanel, type QuestionnairePanelProps } from './QuestionnairePanel.tsx'

export interface NodeInspectorProps {
  detail: ValuationWorkflowNodeView
  stale: boolean
  busy: boolean
  retryAnswer: string
  canRetry: boolean
  onRetryAnswerChange: (value: string) => void
  onRetrySubmit: () => void
  onRetryNode?: () => void
  onOpenSession?: (sessionId: string) => void
  /** Only questions the Host attributes to this exact node are rendered here. */
  clarification?: ValuationWorkflowClarification | null
  answers?: Record<string, string>
  onAnswerChange?: (field: string, value: string) => void
  onSubmitClarification?: (clarificationId: string, answers: Record<string, string>) => void
  questionnaireProps?: QuestionnairePanelProps
}

function isRecord(value: unknown): value is Record<string, unknown> {
  return value !== null && typeof value === 'object' && !Array.isArray(value)
}

interface DisplayField {
  field: string
  label: string
  source: string
  sourceKind?: ValuationWorkflowFieldSourceKind
  value: unknown
}

/**
 * Keep the projected fields and append any raw receipt keys the projection omitted.
 *
 * The raw record itself is never shown as a separate panel; it only prevents a field
 * from disappearing between the Host projection and the structured value view.
 */
function displayFieldsOf(
  fields: ValuationWorkflowNodeFieldView[],
  raw: unknown,
): DisplayField[] {
  const out: DisplayField[] = fields.map((field) => ({
    field: field.field,
    label: field.label,
    source: field.source,
    sourceKind: field.sourceKind,
    value: field.rawValue === undefined ? field.value : field.rawValue,
  }))
  if (!isRecord(raw)) return out
  const known = new Set(out.map((field) => field.field))
  for (const [key, value] of Object.entries(raw)) {
    if (known.has(key)) continue
    out.push({ field: key, label: key, source: '原始记录', value })
  }
  return out
}

function ReadOnlyFields(props: { fields: DisplayField[] }): React.ReactElement {
  if (props.fields.length === 0) return <p className={W.hint}>本次没有可显示的字段。</p>
  return <ul className={W.fields}>
    {props.fields.map((field) => {
      const kind = sourceKindLabelOf(field.sourceKind)
      return <li className={W.fieldRow} key={field.field}>
        <span className={W.fieldLabel}>{field.label}</span>
        <span className={W.fieldValue} data-workflow-field-value={field.field}>
          <StructuredValue value={field.value} />
        </span>
        {kind === null ? null : <span className={W.fieldKind}>{kind}</span>}
        <span className={W.fieldSource}>{field.source}</span>
      </li>
    })}
  </ul>
}

/**
 * Node drawer body: the current session action, real unresolved gaps with one
 * supplemental-answer retry form, then the read-only current input and output.
 *
 * Correction provenance is generated by the adapter; the drawer no longer asks the
 * employee to type a reason/source or shows read-source, knowledge, dependants or a
 * separate raw-record panel.
 */
export function NodeInspector(props: NodeInspectorProps): React.ReactElement {
  const { detail } = props
  const identity = `${detail.nodeId}:${String(detail.revision)}`
  const [expanded, setExpanded] = React.useState({ identity, input: false, output: false })
  const inputOpen = expanded.identity === identity && expanded.input
  const outputOpen = expanded.identity === identity && expanded.output
  const toggleSection = (section: 'input' | 'output', open: boolean): void => {
    setExpanded((previous) => ({
      ...(previous.identity === identity ? previous : { identity, input: false, output: false }),
      [section]: open,
    }))
  }
  const inputs = Array.isArray(detail.inputs) ? detail.inputs : []
  const outputs = Array.isArray(detail.outputs) ? detail.outputs : []
  const gaps = Array.isArray(detail.gaps) ? detail.gaps : []
  const sessionId = typeof detail.sessionId === 'string' ? detail.sessionId : ''
  const showSession = sessionId !== '' && detail.current !== false
  const clarification = props.clarification ?? null
  const retryDisabled = props.busy || props.stale || !props.canRetry
  const failure = detail.failure
  const executionFault = failure !== undefined && failure.kind !== 'business'

  return <section className={W.detail} data-workflow-node-detail={detail.nodeId}
    data-workflow-node-current={String(detail.current !== false)}>
    {showSession
      ? <div className={W.session} data-workflow-node-session={sessionId}>
        <span className={W.fieldLabel}>当前节点会话</span>
        <span className={W.mono}>{sessionId}</span>
        {typeof props.onOpenSession === 'function'
          ? <Button variant="secondary" size="sm" data-workflow-open-node-session="true"
            onClick={() => { props.onOpenSession?.(sessionId) }}>打开节点会话</Button>
          : null}
      </div>
      : null}

    {failure === undefined ? null : <div className={W.block} data-workflow-node-failure={failure.kind} role="status">
      <h4 className={W.blockTitle}>{executionFault ? '执行失败原因' : '节点受阻原因'}</h4>
      <p className={W.gapItem}>{failure.reason}</p>
      <h4 className={W.blockTitle}>未满足的要求</h4>
      <ul className={W.fields}>{failure.requirements.map((item, index) => <li className={W.gapItem} key={index}>{item}</li>)}</ul>
      <h4 className={W.blockTitle}>下一步处理</h4>
      <ul className={W.fields}>{failure.actions.map((item, index) => <li className={W.hint} key={index}>{item}</li>)}</ul>
      {executionFault && props.onRetryNode !== undefined ? <Button variant="secondary" size="sm"
        data-workflow-node-retry="true" disabled={props.busy || props.stale || props.questionnaireProps?.running === true}
        onClick={() => { props.onRetryNode?.() }}>重新执行该节点</Button> : null}
    </div>}

    {props.questionnaireProps === undefined ? null : <QuestionnairePanel {...props.questionnaireProps} executionBlocked={executionFault} />}

    {props.questionnaireProps !== undefined || clarification === null || typeof props.onSubmitClarification !== 'function'
      ? null
      : <ClarificationPanel
        clarification={clarification}
        answers={props.answers ?? {}}
        busy={props.busy}
        onAnswerChange={props.onAnswerChange ?? (() => {})}
        onSubmit={props.onSubmitClarification}
      />}

    {failure !== undefined || gaps.length === 0
      ? null
      : <div className={W.block} data-workflow-detail="gaps">
        <h4 className={W.blockTitle}>未核与缺口</h4>
        <ul className={W.fields}>
          {gaps.map((gap) => <li className={W.gapItem} key={gap}>{gap}</li>)}
        </ul>
      </div>}

    {props.questionnaireProps !== undefined ? null : <div className={W.retry} data-workflow-retry-form="true"
      data-workflow-retry-stale={String(props.stale)}>
      <label className={W.retryField} htmlFor={`crwu-workflow-retry-${detail.nodeId}`}>
        补充说明（会作为本次追问发送给该节点）
      </label>
      <textarea
        id={`crwu-workflow-retry-${detail.nodeId}`}
        className={W.retryInput}
        data-workflow-retry-answer="true"
        rows={3}
        value={props.retryAnswer}
        disabled={props.busy}
        onChange={(event) => { props.onRetryAnswerChange(event.currentTarget.value) }}
      />
      {props.stale
        ? <p className={W.stale} data-workflow-revision-stale="true">节点已有新版本，请刷新后按最新版本重试</p>
        : null}
      {props.busy ? <p className={W.hint}>正在提交，请稍候…</p> : null}
      <button
        type="button"
        className={`${W.submit} crwu-ui-btn crwu-ui-btn-primary crwu-ui-btn-sm`}
        data-workflow-retry-submit="true"
        disabled={retryDisabled}
        onClick={() => { if (!retryDisabled) props.onRetrySubmit() }}
      >补充并重新执行</button>
    </div>}

    <details className={W.block} data-workflow-detail="input" open={inputOpen}
      onToggle={(event) => { toggleSection('input', event.currentTarget.open) }}>
      <summary className={W.blockTitle}>本次输入（只读）</summary>
      {inputOpen ? <ReadOnlyFields fields={displayFieldsOf(inputs, detail.rawInputs)} /> : null}
    </details>

    <details className={W.block} data-workflow-detail="output" open={outputOpen}
      onToggle={(event) => { toggleSection('output', event.currentTarget.open) }}>
      <summary className={W.blockTitle}>本次输出（只读）</summary>
      {outputOpen ? <ReadOnlyFields fields={displayFieldsOf(outputs, detail.rawOutputs)} /> : null}
    </details>
  </section>
}
