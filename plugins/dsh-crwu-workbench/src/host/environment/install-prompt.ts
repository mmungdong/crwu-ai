/**
 * 安装提示词全文。
 *
 * **这段文本是交给另一个 agent 的作业指令**，那个 agent 会照着它在本机完成登录与密钥配置。
 *
 * 2026-09-25 起**不再外链任何安装清单**。原来第一篇就是「先完整阅读这份安装清单 —— <url>」，
 * 而那个 URL 来自只读 OSS：既意味着员工的安装行为依赖一个远端对象，也意味着**任何人都能换掉
 * 那个地址**，把 agent 引到别处去下载东西。现在 `crwu` / `dws` / `ossutil` 随插件发布在包内
 * `bin/<平台>/`，本机零安装，剩下的只有登录与密钥 —— 于是提示词整篇自述，一个外链都没有。
 *
 * 措辞里两处是安全相关的，改写时不要弄丢（它们曾经被"意思差不多"地改写过一次）：
 * - 「GitHub 一律按不可达处理」—— 本环境按不可达处理，去探测会白等；
 * - 「密钥、令牌一律不要回显」。
 *
 * **2026-09-25 补充口径**：登录**不再**让 agent 拼 `crwu h3yun session login` / `dws auth login`，
 * 而是让它在面板「④ 登录与凭据授权」里点对应的登录按钮 —— 那两条命令由插件按 DSH 的审批契约、
 * 用**包内绝对路径**发起，员工机器上因此不需要任何 PATH 配置（`~/bin` 或插件 bin 目录
 * prepend 进 shell PATH 这类老做法都不再需要，也不要再写回来）。
 */

/** 随插件发布、**不需要** agent 安装的三个命令。改这个列表要同步 `scripts/sync-binaries.mjs`。 */
export const BUNDLED_TOOLS = ['crwu', 'dws', 'ossutil'] as const

/**
 * 生成安装提示词。
 *
 * 只收 `workspacePath`：没有清单地址可传了 —— 少了这个参数，就少了一条「把 agent 引到任意 URL」
 * 的通道。文本里的每一项都是本机自己的动作。
 */
export function buildInstallPromptText(workspacePath: unknown): string {
  const space = String(workspacePath ?? '')
  const L = []
  L.push('请完成本机 crwu 审核环境的配置。')
  L.push('')
  L.push(`**先看清哪部分不用做**：${BUNDLED_TOOLS.join(' / ')} 由中瑞世联工作台插件**随包自带**`
    + '（在插件自己的 `bin/<平台>/` 目录里，版本与插件锁定）。**不要**下载、安装或升级它们，'
    + '也不要往 `~/bin` 或任何系统目录里放副本 —— 那只会和插件自带的那份打架。')
  L.push('')
  L.push('需要你做的只有登录与密钥这几项，逐条检查、只做缺的：')
  L.push('1. **氚云登录**：在插件面板「④ 登录与凭据授权（氚云 / 钉钉）」里点「氚云登录」，'
    + '按提示用手机钉钉扫码。这一步由**插件自己**按 DSH 的审批契约发起，'
    + '**不要**在 shell 里手工拼 `crwu` 命令。')
  L.push('2. **钉钉登录**：同一层里点「钉钉登录」，按提示完成授权；'
    + '浏览器打不开时用「设备码登录（浏览器打不开时）」。同样**不要**手工拼 `dws` 命令。')
  L.push('3. **先完成插件授权**：首次会弹出「同意并继续」（授权插件读取本机凭据）。'
    + '没授权时面板会如实显示「需要授权」，**不是**「未登录」—— 不要据此判断员工没登录，也不要绕过去。')
  L.push('4. **阿里云 OSS 凭据**：由员工在中瑞世联工作台的环境自检页「⑤ OSS 交付配置」里自己填写 AccessKey ID / Secret。'
    + '**你不要索取、不要代填、也不要让它出现在对话或文件里。**')
  L.push('5. **iFinD 密钥**：技能配置文件里的 `auth_token` 必须有效。缺失或仍是占位符时**停下来告诉我**，'
    + '不要把密钥贴进对话。')
  L.push('')
  L.push('几条必须遵守的：')
  L.push('1. **先检查、只做缺的**：已经登录好、已经配好的项直接跳过，不要重做。')
  L.push('2. **GitHub 一律按不可达处理**：不要尝试、不要兜底、不要试探连通性。需要的东西只能从 GitHub 获得时停下来问我。')
  L.push('3. **密钥、令牌一律不要回显**到对话或日志里。')
  L.push('4. **每一项都要实际验证**（在面板上看真实状态、看真实输出），不要凭推理判断成功。')
  L.push('5. **不要去找这几个命令的路径**：不要搜索可执行文件、不要改 PATH、不要把命令复制到 `~/bin` 或系统目录、'
    + '不要为了「让它能跑」而调环境 —— 插件用**包内绝对路径**启动它们，本机不需要任何 PATH 配置。')
  if (space !== '') {
    L.push(`6. 需要临时文件时放在当前工作空间 \`${space}\` 下，不要写系统目录。`)
  }
  L.push('')
  L.push('完成后**逐项回报**：每项的实际状态（新做/已存在）、验证命令的真实输出；以及任何跳过或失败的项目和原因。')
  return L.join('\n')
}
