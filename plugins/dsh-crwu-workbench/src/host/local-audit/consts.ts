/**
 * 本地审核（协议 28）的固定常量。
 *
 * 这些值都是**产品约束**，不是实现细节：上限、有效期、目录名会被写进提示词、界面文案与测试，
 * 所以只在这里出现一次。
 */

/** 单次审核的普通文件上限。超过时**明确阻止**，绝不静默截取前 30 个。 */
export const LOCAL_AUDIT_MAX_FILES = 30

/** 一次性 handoff 的有效期（用户复制提示词后太久没发就会过期）。 */
export const LOCAL_AUDIT_HANDOFF_TTL_MS = 30 * 60_000

/**
 * 本地审核案例目录的**父目录名**（在员工选定的工作空间下）。
 *
 * ⚠️ 2026-10-11 用户实测后改的：本地审核的案例目录**曾经**在操作系统临时目录下，
 * 两个后果都不能接受 ——
 * ① 会话 cwd 只能是那个临时目录，于是这条会话**永远落「未分组」**（用户要求"创建在我
 *    环境信息规定的工作区下面"）；而把 cwd 设成工作空间的话，临时目录在沙箱之外，
 *    对话里的案例内工具（非特权）又写不进去；
 * ② 交付件躺在系统临时目录里，用户根本找不到（而且会被清理逻辑删掉，见 `handoff.ts`）。
 *
 * 现在它落在 `<工作空间>/本地审核/<handoffId>/`：会话 cwd = 工作空间（分组正确、沙箱边界
 * 正好罩住案例目录），交付件也在用户自己的目录里找得到。
 * 这符合仓规「插件只允许在工作空间下创建 Host 推导出来的案例目录」。
 */
export const LOCAL_AUDIT_CASE_PARENT_DIR = '本地审核'

/** 快照里材料目录名：与审核链路共用同一个名字（`host/tools/consts.ts` 的 `CASE_MATERIAL_DIR`）。 */
export const LOCAL_AUDIT_SOURCE_DIR = '材料-源'

/** 快照里「读到了什么」的清单（人可读，模型也读它）。 */
export const LOCAL_AUDIT_MANIFEST_FILE = '本地审核清单.json'

/** 快照元数据：handoffId、时刻、计数、指纹。 */
export const LOCAL_AUDIT_META_FILE = '快照元数据.json'

/**
 * 扫描时的**安全上限**：一个选择项最多枚举多少个条目。
 *
 * 它不是业务上限（业务上限是 30 个文件）—— 用户可能误选了一个巨大的目录。
 * 到顶就停止枚举并如实说明，而不是把整个磁盘读完再回答。
 */
export const LOCAL_AUDIT_SCAN_MAX_ENTRIES = 20_000

/** 每个选择项展开后最多保留多少个普通文件候选（防止误选巨型目录时撑爆内存）。 */
export const LOCAL_AUDIT_SCAN_MAX_FILES = 2_000
